#!/usr/bin/env bash
#
# The production secrets: ansible/inventory/production/group_vars/all/vault.yml.
#
#   scripts/vault.sh init       generate every secret and write the encrypted vault
#   scripts/vault.sh edit       open it in $EDITOR
#   scripts/vault.sh view       print it, decrypted
#   scripts/vault.sh public     print the public halves: what goes in DNS and on the NAS
#   scripts/vault.sh generate   print a fresh set of secrets, unencrypted, to stdout
#
# The file is committed encrypted. Its password is not committed anywhere: it belongs in
# the password manager (ADR 0002). If ansible/.vault-pass exists — it is gitignored — it is
# used; otherwise you are asked.
#
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
VAULT="$ROOT/ansible/inventory/production/group_vars/all/vault.yml"
PASS="$ROOT/ansible/.vault-pass"

[[ -x "$ROOT/.venv/bin/ansible-vault" ]] && PATH="$ROOT/.venv/bin:$PATH"

# An array rather than a function printing lines: macOS still ships bash 3.2, which has
# no mapfile to read them back with.
VAULT_ARGS=(--ask-vault-pass)
[[ -f "$PASS" ]] && VAULT_ARGS=(--vault-password-file "$PASS")

indent() { sed 's/^/  /'; }

generate() {
    local tmp
    tmp=$(mktemp -d)
    # shellcheck disable=SC2064  # expand now: the directory to remove is this one
    trap "rm -rf '$tmp'" RETURN
    ssh-keygen -q -t ed25519 -N '' -C site-backup -f "$tmp/backup"
    openssl genrsa -out "$tmp/dkim.pem" 2048 2>/dev/null
    cat <<YAML
# Generated by scripts/vault.sh. Each value exists here and on the host, nowhere else.

# Signs session cookies, the client-gallery unlock cookie and password-reset links.
vault_django_secret_key: "$(python3 -c 'import secrets; print(secrets.token_urlsafe(64))')"

# Where the admin is mounted: a shared secret on top of the admin password.
vault_django_admin_path: "$(python3 -c 'import secrets; print(secrets.token_hex(10))')/"

# Signs outgoing mail. Its public half is published in DNS (scripts/vault.sh public).
vault_dkim_private_key: |
$(indent <"$tmp/dkim.pem")

# What the server logs in to the NAS with. Its public half goes in the NAS's authorized_keys.
vault_backup_ssh_private_key: |
$(indent <"$tmp/backup")
YAML
}

case "${1:-}" in
    generate)
        generate
        ;;

    init)
        if [[ -f "$VAULT" ]]; then
            echo "A vault already exists at ${VAULT#"$ROOT"/}." >&2
            echo "Replacing it would orphan every secret the host is using. Delete it first if you mean to." >&2
            exit 1
        fi
        # Encrypted in memory and written once: the plaintext never touches the disk.
        generate | ansible-vault encrypt "${VAULT_ARGS[@]}" --output "$VAULT" /dev/stdin
        echo "✓ Wrote ${VAULT#"$ROOT"/} (encrypted). Commit it."
        echo "  Keep the vault password in the password manager — it is the only copy of the key."
        ;;

    edit | view)
        ansible-vault "$1" "${VAULT_ARGS[@]}" "$VAULT"
        ;;

    public)
        plain=$(ansible-vault view "${VAULT_ARGS[@]}" "$VAULT")
        tmp=$(mktemp -d)
        trap 'rm -rf "$tmp"' EXIT
        # Pull the two block scalars out without a YAML library on the path.
        awk -v dir="$tmp" '
            /^vault_dkim_private_key:/        { out = dir "/dkim.pem"; next }
            /^vault_backup_ssh_private_key:/  { out = dir "/backup"; next }
            /^[^ ]/                           { out = "" }
            out != "" && /^  /                { sub(/^  /, ""); print > out }
        ' <<<"$plain"
        chmod 600 "$tmp/backup" "$tmp/dkim.pem"
        echo "Backup key — add this line to the backup account's authorized_keys on the NAS:"
        echo
        echo "  $(ssh-keygen -y -f "$tmp/backup")"
        echo
        echo "DKIM — publish as a TXT record at mail._domainkey.<your domain>:"
        echo
        echo "  v=DKIM1; k=rsa; p=$(openssl rsa -in "$tmp/dkim.pem" -pubout -outform DER 2>/dev/null | base64 | tr -d '\n')"
        ;;

    *)
        echo "usage: scripts/vault.sh <init|edit|view|public|generate>" >&2
        exit 2
        ;;
esac
